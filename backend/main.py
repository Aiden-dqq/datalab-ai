class AnalyzeRequest(BaseModel):
    csv_text: str = ""
    dataset_name: str = "experiment.csv"
    protocol_context: Optional[str] = None
    input_kind: str = "text"
    file_base64: Optional[str] = None
    media_type: Optional[str] = None
    experiment_steps: Optional[str] = None


@app.post("/api/analyze")
async def create_analysis(req: AnalyzeRequest) -> dict:
    result = analyze_dataset(
        csv_text=req.csv_text,
        dataset_name=req.dataset_name,
        protocol_context=req.protocol_context,
        input_kind=req.input_kind,
        file_base64=req.file_base64,
        media_type=req.media_type,
        experiment_steps=req.experiment_steps,
    )
    if not result["ok"]:
        raise HTTPException(status_code=400, detail=result["error"])
    return result["data"]


